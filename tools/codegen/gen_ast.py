#!/usr/bin/env python3
"""Generates the AST node model of crates/dartr_ast from its schema.

Input: crates/dartr_ast/schema/ast.json, extracted from the pinned analyzer
(`pkg/analyzer/lib/src/dart/ast/ast.dart`, `@GenerateNodeImpl` annotations,
and `GeneralizingAstVisitor` of `lib/dart/ast/visitor.g.dart`) with

    (cd tools/oracle && dart run bin/ast_schema.dart > ../../crates/dartr_ast/schema/ast.json)

Output: crates/dartr_ast/src/generated/{nodes,children,visitor,copy}.rs. Run from
the repository root:

    python3 tools/codegen/gen_ast.py

The generated code follows the rules of the Dart generator
(`pkg/analyzer/tool/generators/ast_generator.dart`): `beginToken`,
`endToken`, `firstTokenAfterCommentAndMetadata`, `_childEntities`,
`visitChildren`, `replaceChild` and `removeChild` come from the order and the
kinds of the properties in `childEntitiesOrder`.
"""
import json
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCHEMA = os.path.join(ROOT, 'crates/dartr_ast/schema/ast.json')
OUT = os.path.join(ROOT, 'crates/dartr_ast/src/generated')

HEADER = '''// GENERATED FILE. DO NOT EDIT.
// Generated by tools/codegen/gen_ast.py from crates/dartr_ast/schema/ast.json.
// Dart source: pkg/analyzer/lib/src/dart/ast/ast.dart
'''

RUST_KEYWORDS = {'type': 'type_'}

# Interfaces of ast.dart that are not node categories.
SKIP_INTERFACES = {'SyntheticIdentifier', 'ForLoop'}

# Nodes without `@GenerateNodeImpl`: properties written here, begin/end
# tokens and child entities are hand-written (src/node_impl.rs).
MANUAL = {
    'Comment': [
        {'name': 'references', 'kind': 'node_list', 'nullable': False, 'type': 'CommentReference'},
        {'name': 'tokens', 'kind': 'token_list', 'nullable': False},
        {'name': 'codeBlocks', 'kind': 'other', 'nullable': False, 'dart_type': 'List<MdCodeBlock>'},
        {'name': 'docImports', 'kind': 'other', 'nullable': False, 'dart_type': 'List<DocImport>'},
        {'name': 'docDirectives', 'kind': 'other', 'nullable': False, 'dart_type': 'List<DocDirective>'},
        {'name': 'hasNodoc', 'kind': 'other', 'nullable': False, 'dart_type': 'bool'},
    ],
    'CompilationUnit': [
        {'name': 'beginToken', 'kind': 'token', 'nullable': False, 'not_child': True},
        {'name': 'scriptTag', 'kind': 'node', 'nullable': True, 'type': 'ScriptTag'},
        {'name': 'directives', 'kind': 'node_list', 'nullable': False, 'type': 'Directive'},
        {'name': 'declarations', 'kind': 'node_list', 'nullable': False, 'type': 'CompilationUnitMember'},
        {'name': 'endToken', 'kind': 'token', 'nullable': False, 'not_child': True},
    ],
}

# Nodes that are not part of the syntax tree (`ConstantContextForExpression`
# is created by the constant evaluator, it has no visitor method).
SKIP_NODES = {'ConstantContextForExpression'}

# `other` properties: the Rust type, or None for resolution data, which is
# kept in side tables (see the crate documentation).
OTHER_TYPES = {
    'bool': 'bool',
    'double': 'f64',
    'int?': 'Option<i64>',
    'String': 'Box<str>',
    'ParameterKind': 'ParameterKind',
    'List<MdCodeBlock>': 'Vec<MdCodeBlock>',
    'List<DocImport>': 'Vec<DocImport>',
    'List<DocDirective>': 'Vec<DocDirective>',
    'ExtensionElementImpl': None,
    'MethodElement?': None,
    'List<DartType>': None,
}


def snake(name):
    s = re.sub(r'(?<=[a-z0-9])([A-Z])', r'_\1', name)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    return s.lower()


def field(name):
    s = snake(name)
    return RUST_KEYWORDS.get(s, s)


def load():
    with open(SCHEMA) as f:
        schema = json.load(f)
    nodes = []
    for n in schema['nodes']:
        if n['name'] in SKIP_NODES:
            continue
        props = n.get('properties')
        if props is None:
            props = MANUAL[n['name']]
        props = [dict(p) for p in props]
        for p in props:
            if p['kind'] == 'other':
                p['rust_type'] = OTHER_TYPES[p['dart_type']]
        n = dict(n)
        n['props'] = [p for p in props if not (p['kind'] == 'other' and p['rust_type'] is None)]
        n['manual'] = n['name'] in MANUAL
        n['dump_name'] = n['impl'][:-4] if n['impl'].endswith('Impl') else n['impl']
        nodes.append(n)
    nodes.sort(key=lambda n: n['name'])
    interfaces = {k: v for k, v in schema['interfaces'].items() if k not in SKIP_INTERFACES}
    for v in interfaces.values():
        v['supertypes'] = [s for s in v['supertypes'] if s not in SKIP_INTERFACES]
        v['all_supertypes'] = [s for s in v['all_supertypes'] if s not in SKIP_INTERFACES]
    return schema, nodes, interfaces


def all_props(n):
    """Properties including the comment and metadata of annotated nodes."""
    pre = []
    if n['annotated']:
        pre = [
            {'name': 'documentationComment', 'kind': 'node', 'nullable': True, 'type': 'Comment', 'annotated_prefix': True},
            {'name': 'metadata', 'kind': 'node_list', 'nullable': False, 'type': 'Annotation', 'annotated_prefix': True},
        ]
    return pre + n['props']


def rust_type(p):
    k = p['kind']
    if k == 'token':
        return 'Option<TokenId>' if p['nullable'] else 'TokenId'
    if k == 'token_list':
        return 'TokenList'
    if k == 'node':
        t = 'Id<%s>' % p['type']
        return 'Option<%s>' % t if p['nullable'] else t
    if k == 'node_list':
        return 'NodeList<%s>' % p['type']
    return p['rust_type']


def gen_nodes(schema, nodes, interfaces):
    concrete = [n['name'] for n in nodes]
    out = [HEADER]
    out.append('''
//! Node structs, node kinds, node categories (the abstract Dart interfaces)
//! and the reflection table.

#![allow(clippy::all)]

use dartr_syntax::TokenId;

use crate::arena::{Concrete, Id, NodeList, NodeType, SubtypeOf, TokenList};
use crate::doc_comment::{DocDirective, DocImport, MdCodeBlock};
use crate::node_impl::ParameterKind;

/// The kind of a node: one value per concrete node class of the analyzer
/// (Dart `XImpl`).
#[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Debug)]
#[repr(u8)]
pub enum NodeKind {
''')
    for n in nodes:
        out.append('    %s,\n' % n['name'])
    out.append('}\n\n')
    out.append('impl NodeKind {\n')
    out.append('    pub const COUNT: usize = %d;\n\n' % len(nodes))
    out.append('    pub const ALL: [NodeKind; %d] = [\n' % len(nodes))
    for n in nodes:
        out.append('        NodeKind::%s,\n' % n['name'])
    out.append('    ];\n\n')
    out.append('    /// The Dart name of the node class without `Impl` (the `t` of the\n')
    out.append('    /// `ast` dump: `runtimeType` without `Impl`).\n')
    out.append('    pub fn name(self) -> &\'static str {\n        NODE_INFOS[self as usize].name\n    }\n\n')
    out.append('    pub fn info(self) -> &\'static NodeInfo {\n        &NODE_INFOS[self as usize]\n    }\n')
    out.append('}\n\n')

    # Structs.
    for n in nodes:
        out.append('/// Dart `%s`.\n' % n['impl'])
        sup = interfaces.get(n['name'], {}).get('all_supertypes', [])
        if sup:
            out.append('///\n/// Supertypes: %s.\n' % ', '.join('`%s`' % s for s in sup))
        out.append('#[derive(Clone, Debug)]\npub struct %s {\n' % n['name'])
        for p in all_props(n):
            doc = 'Dart `%s`' % p['name']
            if p.get('is_super'):
                doc += ' (declared in a superclass)'
            if p.get('not_child'):
                doc += ' (not a child entity)'
            out.append('    /// %s.\n' % doc)
            out.append('    pub %s: %s,\n' % (field(p['name']), rust_type(p)))
        out.append('}\n\n')
        out.append('impl NodeType for %s {\n' % n['name'])
        out.append('    const NAME: &\'static str = "%s";\n' % n['name'])
        subs = [m['name'] for m in nodes if m['name'] == n['name'] or n['name'] in interfaces.get(m['name'], {}).get('all_supertypes', [])]
        out.append('    #[inline]\n    fn test(kind: NodeKind) -> bool {\n')
        out.append('        matches!(kind, %s)\n    }\n}\n\n' % ' | '.join('NodeKind::%s' % s for s in subs))
        out.append('impl Concrete for %s {\n' % n['name'])
        out.append('    const KIND: NodeKind = NodeKind::%s;\n' % n['name'])
        out.append('    #[inline]\n    fn store(stores: &Stores) -> &Vec<Self> {\n        &stores.%s\n    }\n' % snake(n['name']))
        out.append('    #[inline]\n    fn store_mut(stores: &mut Stores) -> &mut Vec<Self> {\n        &mut stores.%s\n    }\n' % snake(n['name']))
        out.append('}\n\n')
        for s in sup:
            if s in SKIP_INTERFACES:
                continue
            out.append('impl SubtypeOf<%s> for %s {}\n' % (s, n['name']))
        out.append('\n')

    # Abstract categories.
    out.append('// Node categories: the abstract Dart interfaces (`Expression`,\n')
    out.append('// `Statement`, ...). They are only used as type parameters of `Id`.\n\n')
    for name in sorted(interfaces):
        if name in concrete:
            continue
        v = interfaces[name]
        out.append('/// Dart `%s` (abstract).\n' % name)
        out.append('#[derive(Debug)]\npub enum %s {}\n\n' % name)
        subs = [m['name'] for m in nodes if name in interfaces.get(m['name'], {}).get('all_supertypes', [])]
        out.append('impl NodeType for %s {\n' % name)
        out.append('    const NAME: &\'static str = "%s";\n' % name)
        out.append('    #[inline]\n    fn test(kind: NodeKind) -> bool {\n')
        if name == 'AstNode':
            out.append('        let _ = kind;\n        true\n    }\n}\n\n')
        elif subs:
            out.append('        matches!(kind, %s)\n    }\n}\n\n' % ' | '.join('NodeKind::%s' % s for s in subs))
        else:
            out.append('        let _ = kind;\n        false\n    }\n}\n\n')
        for s in v['all_supertypes']:
            out.append('impl SubtypeOf<%s> for %s {}\n' % (s, name))
        out.append('\n')

    # Stores.
    out.append('/// The node storage of an [`crate::Ast`]: one vector per node kind.\n')
    out.append('#[derive(Clone, Debug, Default)]\npub struct Stores {\n')
    for n in nodes:
        out.append('    pub %s: Vec<%s>,\n' % (snake(n['name']), n['name']))
    out.append('}\n\n')

    # Reflection.
    out.append('''/// The kind of a field of a node.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum FieldKind {
    Token,
    TokenList,
    Node,
    NodeList,
    /// A value that is not a child (for example `IntegerLiteral.value`).
    Other,
}

/// A field of a node, in `childEntities` order.
#[derive(Debug)]
pub struct FieldInfo {
    /// The Dart name of the property.
    pub name: &'static str,
    pub kind: FieldKind,
    pub nullable: bool,
    /// The Dart type of a node field or of the elements of a node list.
    pub ty: &'static str,
    /// Tests whether a node kind is a subtype of [ty].
    pub accepts: fn(NodeKind) -> bool,
    /// Whether the field is a child entity (false for
    /// `CompilationUnit.beginToken` and `endToken`).
    pub child: bool,
}

/// Information about a node kind (the schema at run time).
#[derive(Debug)]
pub struct NodeInfo {
    /// Dart name without `Impl`.
    pub name: &'static str,
    pub kind: NodeKind,
    /// Whether the node is a Dart `AnnotatedNode` (the first two fields
    /// are the documentation comment and the metadata).
    pub annotated: bool,
    /// All supertypes (Dart interfaces).
    pub supertypes: &'static [&'static str],
    pub fields: &'static [FieldInfo],
}

fn accepts_none(_: NodeKind) -> bool {
    false
}

pub static NODE_INFOS: [NodeInfo; NodeKind::COUNT] = [
''')
    kind_name = {'token': 'Token', 'token_list': 'TokenList', 'node': 'Node', 'node_list': 'NodeList', 'other': 'Other'}
    for n in nodes:
        out.append('    NodeInfo {\n')
        out.append('        name: "%s",\n' % n['dump_name'])
        out.append('        kind: NodeKind::%s,\n' % n['name'])
        out.append('        annotated: %s,\n' % ('true' if n['annotated'] else 'false'))
        sup = interfaces.get(n['name'], {}).get('all_supertypes', [])
        out.append('        supertypes: &[%s],\n' % ', '.join('"%s"' % s for s in sup))
        out.append('        fields: &[\n')
        for p in all_props(n):
            ty = p.get('type', '')
            acc = '<%s as NodeType>::test' % ty if ty else 'accepts_none'
            out.append('            FieldInfo { name: "%s", kind: FieldKind::%s, nullable: %s, ty: "%s", accepts: %s, child: %s },\n' % (
                p['name'], kind_name[p['kind']], 'true' if p['nullable'] else 'false', ty, acc,
                'false' if p.get('not_child') else 'true'))
        out.append('        ],\n    },\n')
    out.append('];\n')
    return ''.join(out)


def begin_token_body(n, props, indent='        '):
    """Port of `_generateBeginToken`."""
    lines = []
    found = False
    i = 0
    while i < len(props):
        p = props[i]
        name = field(p['name'])
        k = p['kind']
        if k == 'token' and p.get('token_group') is not None:
            g = p['token_group']
            group = []
            while i < len(props) and props[i]['kind'] == 'token' and props[i].get('token_group') == g:
                group.append(props[i])
                i += 1
            args = ', '.join(('self.%s' % field(q['name'])) if q['nullable'] else ('Some(self.%s)' % field(q['name'])) for q in group)
            lines.append('if let Some(result) = lexically_first(&ast.tokens, &[%s]) {' % args)
            lines.append('    return result;')
            lines.append('}')
            continue
        i += 1
        if k == 'token':
            if p['nullable']:
                lines.append('if let Some(%s) = self.%s {' % (name, name))
                lines.append('    return %s;' % name)
                lines.append('}')
            else:
                lines.append('return self.%s;' % name)
                found = True
                break
        elif k == 'token_list':
            lines.append('return ast.token_list(self.%s)[0];' % name)
            found = True
            break
        elif k == 'node':
            if p['nullable']:
                lines.append('if let Some(%s) = self.%s {' % (name, name))
                lines.append('    return ast.begin_token(%s);' % name)
                lines.append('}')
            else:
                lines.append('return ast.begin_token(self.%s);' % name)
                found = True
                break
        elif k == 'node_list':
            lines.append('if let Some(result) = ast.list_begin_token(self.%s) {' % name)
            lines.append('    return result;')
            lines.append('}')
    if not found:
        lines.append('panic!("Expected at least one non-null")')
    return '\n'.join(indent + l for l in lines) + '\n'


def end_token_body(n, props, indent='        '):
    """Port of `_generateEndToken`."""
    lines = []
    found = False
    for p in reversed(props):
        name = field(p['name'])
        k = p['kind']
        if k == 'token':
            if p['nullable']:
                lines.append('if let Some(%s) = self.%s {' % (name, name))
                lines.append('    return %s;' % name)
                lines.append('}')
            else:
                lines.append('return self.%s;' % name)
                found = True
                break
        elif k == 'token_list':
            lines.append('return *ast.token_list(self.%s).last().unwrap();' % name)
            found = True
            break
        elif k == 'node':
            if p['nullable']:
                lines.append('if let Some(%s) = self.%s {' % (name, name))
                lines.append('    return ast.end_token(%s);' % name)
                lines.append('}')
            else:
                lines.append('return ast.end_token(self.%s);' % name)
                found = True
                break
        elif k == 'node_list':
            lines.append('if let Some(result) = ast.list_end_token(self.%s) {' % name)
            lines.append('    return result;')
            lines.append('}')
    if not found:
        lines.append('panic!("Expected at least one non-null")')
    return '\n'.join(indent + l for l in lines) + '\n'


def gen_children(schema, nodes, interfaces):
    out = [HEADER]
    out.append('''
//! Generated node behavior: begin and end tokens, child entities, child
//! nodes, and replacing and removing children.

#![allow(clippy::all)]
#![allow(unreachable_code, unused_variables)]

use dartr_syntax::TokenId;

use crate::arena::{Ast, Entity, NodeId, NodeType};
use crate::generated::nodes::*;
use crate::token::lexically_first;

''')
    for n in nodes:
        props = n['props']
        allp = all_props(n)
        out.append('impl %s {\n' % n['name'])
        if not n['manual']:
            if n['annotated']:
                out.append('    /// Dart `firstTokenAfterCommentAndMetadata`.\n')
                out.append('    pub fn first_token_after_comment_and_metadata(&self, ast: &Ast) -> TokenId {\n')
                out.append(begin_token_body(n, props))
                out.append('    }\n\n')
                out.append('    /// Dart `beginToken` (`_AnnotatedNodeMixin`).\n')
                out.append('    pub fn begin_token(&self, ast: &Ast) -> TokenId {\n')
                out.append('        ast.annotated_begin_token(self.documentation_comment, self.metadata)\n')
                out.append('            .unwrap_or_else(|| self.first_token_after_comment_and_metadata(ast))\n')
                out.append('    }\n\n')
            else:
                out.append('    /// Dart `beginToken`.\n')
                out.append('    pub fn begin_token(&self, ast: &Ast) -> TokenId {\n')
                out.append(begin_token_body(n, props))
                out.append('    }\n\n')
            out.append('    /// Dart `endToken`.\n')
            out.append('    pub fn end_token(&self, ast: &Ast) -> TokenId {\n')
            out.append(end_token_body(n, props))
            out.append('    }\n\n')
        # child entities (before sorting)
        if not (n['manual'] or 'child_entities' in n.get('manual_parts', []) or n['name'] == 'FormalParameterList'):
            out.append('    /// Dart `_childEntities` (in property order, not sorted).\n')
            out.append('    pub(crate) fn child_entities_unsorted(&self, ast: &Ast, out: &mut Vec<Entity>) {\n')
            for p in allp:
                name = field(p['name'])
                k = p['kind']
                if p.get('not_child'):
                    continue
                if k == 'token':
                    if p['nullable']:
                        out.append('        if let Some(t) = self.%s {\n            out.push(Entity::Token(t));\n        }\n' % name)
                    else:
                        out.append('        out.push(Entity::Token(self.%s));\n' % name)
                elif k == 'token_list':
                    out.append('        out.extend(ast.token_list(self.%s).iter().map(|&t| Entity::Token(t)));\n' % name)
                elif k == 'node':
                    if p['nullable']:
                        out.append('        if let Some(c) = self.%s {\n            out.push(Entity::Node(c.raw()));\n        }\n' % name)
                    else:
                        out.append('        out.push(Entity::Node(self.%s.raw()));\n' % name)
                elif k == 'node_list':
                    out.append('        out.extend(ast.list_raw(self.%s).iter().map(|&c| Entity::Node(c)));\n' % name)
            out.append('    }\n\n')
        # visitChildren order
        out.append('    /// The child nodes in Dart `visitChildren` order.\n')
        out.append('    pub(crate) fn for_each_child(&self, ast: &Ast, f: &mut dyn FnMut(NodeId)) {\n')
        rest = allp
        if n['annotated']:
            out.append('        ast.visit_comment_and_annotations(self.documentation_comment, self.metadata, f);\n')
            rest = props
        if n['name'] == 'CompilationUnit':
            out.append('        if let Some(c) = self.script_tag {\n            f(c.raw());\n        }\n')
            out.append('        ast.visit_directives_and_declarations(self.directives, self.declarations, f);\n')
            rest = []
        for p in rest:
            name = field(p['name'])
            k = p['kind']
            if k == 'node':
                if p['nullable']:
                    out.append('        if let Some(c) = self.%s {\n            f(c.raw());\n        }\n' % name)
                else:
                    out.append('        f(self.%s.raw());\n' % name)
            elif k == 'node_list':
                out.append('        for &c in ast.list_raw(self.%s) {\n            f(c);\n        }\n' % name)
        out.append('    }\n\n')
        # _childContainingRange
        out.append('    /// Dart `_childContainingRange`: the child that contains the range.\n')
        out.append('    pub(crate) fn child_containing_range(&self, ast: &Ast, start: u32, end: u32) -> Option<NodeId> {\n')
        for p in allp:
            name = field(p['name'])
            k = p['kind']
            if k == 'node':
                if p['nullable']:
                    out.append('        if let Some(c) = self.%s {\n            if ast.contains_offset(c, start, end) {\n                return Some(c.raw());\n            }\n        }\n' % name)
                else:
                    out.append('        if ast.contains_offset(self.%s, start, end) {\n            return Some(self.%s.raw());\n        }\n' % (name, name))
            elif k == 'node_list':
                out.append('        if let Some(result) = ast.element_containing_range(self.%s, start, end) {\n            return Some(result);\n        }\n' % name)
        out.append('        None\n    }\n\n')
        # replace child
        out.append('    /// Dart `replaceChild`: replaces [old] with [new] (of kind [kind]) in\n')
        out.append('    /// a child slot. Returns false if [old] is not a child.\n')
        out.append('    pub(crate) fn replace_child(&mut self, lists: &mut [NodeId], old: NodeId, new: NodeId, kind: NodeKind) -> bool {\n')
        for p in allp:
            name = field(p['name'])
            k = p['kind']
            if k == 'node':
                t = p['type']
                if p['nullable']:
                    out.append('        if self.%s.map(|c| c.raw()) == Some(old) {\n' % name)
                    out.append('            assert!(<%s as NodeType>::test(kind), "replaceChild: {kind:?} is not a %s");\n' % (t, t))
                    out.append('            self.%s = Some(crate::arena::Id::from_raw(new));\n            return true;\n        }\n' % name)
                else:
                    out.append('        if self.%s.raw() == old {\n' % name)
                    out.append('            assert!(<%s as NodeType>::test(kind), "replaceChild: {kind:?} is not a %s");\n' % (t, t))
                    out.append('            self.%s = crate::arena::Id::from_raw(new);\n            return true;\n        }\n' % name)
            elif k == 'node_list':
                t = p['type']
                out.append('        if let Some(slot) = self.%s.slots_mut(lists).iter_mut().find(|c| **c == old) {\n' % name)
                out.append('            assert!(<%s as NodeType>::test(kind), "replaceChild: {kind:?} is not a %s");\n' % (t, t))
                out.append('            *slot = new;\n            return true;\n        }\n')
        out.append('        false\n    }\n\n')
        # remove child
        out.append('    /// Dart `removeChild`: clears a nullable child slot that holds [old].\n')
        out.append('    pub(crate) fn remove_child(&mut self, lists: &[NodeId], old: NodeId) -> Result<(), String> {\n')
        for p in allp:
            name = field(p['name'])
            k = p['kind']
            if k == 'node':
                if p['nullable']:
                    out.append('        if self.%s.map(|c| c.raw()) == Some(old) {\n            self.%s = None;\n            return Ok(());\n        }\n' % (name, name))
                else:
                    out.append('        if self.%s.raw() == old {\n            return Err("Cannot remove required child \'%s\'.".into());\n        }\n' % (name, p['name']))
            elif k == 'node_list':
                out.append('        if self.%s.slots(lists).contains(&old) {\n' % name)
                out.append('            return Err("Cannot remove child \'%s\' because NodeList cannot be resized.".into());\n        }\n' % p['name'])
