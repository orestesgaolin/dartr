// Oracle mode `events`: the parser events of the shared ("fasta") parser.
//
// Scans and parses a file the way the analyzer does for `parseString` and
// file analysis (`pkg/analyzer/lib/dart/analysis/utilities.dart`,
// `pkg/analyzer/lib/src/generated/parser.dart`):
//
// - the analyzer `Scanner`, configured with the latest language version
//   (`featureSetForOverriding` and `featureSet`), so that a `// @dart = x.y`
//   comment restricts the features (`scanner.featureSet`);
// - `fasta.Parser(listener, experimentalFeatures:
//   ExperimentalFeaturesStatus(scanner.featureSet))` with the default
//   `useImplicitCreationExpression: true`;
// - `parser.parseUnit(token)` with the first token of the scanner (error
//   tokens first).
//
// Instead of the `AstBuilder`, the listener records every call
// (event_recorder.g.dart, generated by tools/codegen/gen_listener.py).
// The AstBuilder can change the token stream from inside events (it uses
// `parser.rewriter`); a recording listener does not, so the events are the
// events of the parser alone.
//
// Output per file:
//   {"path": ..., "events": [[name, args...], ...],
//    "errors": [[code, offset, length], ...],
//    "stream": [[offset, lexeme] or [offset, lexeme, type] for synthetic
//               tokens, ...]}
// where "stream" is the token stream after parsing, from the first token
// after the error tokens up to EOF.

// ignore_for_file: implementation_imports

import 'dart:io';

import 'package:_fe_analyzer_shared/src/parser/parser.dart' as fasta;
import 'package:_fe_analyzer_shared/src/scanner/error_token.dart';
import 'package:analyzer/dart/analysis/features.dart';
import 'package:analyzer/dart/ast/token.dart';
import 'package:analyzer/error/listener.dart';
import 'package:analyzer/src/dart/analysis/experiments.dart';
import 'package:analyzer/src/dart/scanner/scanner.dart';
import 'package:analyzer/src/error/listener.dart';
import 'package:analyzer/src/string_source.dart';

import 'event_recorder.g.dart';

Map<String, Object?> dumpEvents(String path) {
  var content = File(path).readAsStringSync();
  var featureSet = FeatureSet.latestLanguageVersion();
  var diagnostics = RecordingDiagnosticListener();
  var reporter = DiagnosticReporter(diagnostics, StringSource(content, path));
  var scanner = Scanner(inputText: content, reportError: reporter.report)
    ..configureFeatures(
      featureSetForOverriding: featureSet,
      featureSet: featureSet,
    );
  Token token = scanner.tokenize();

  Token first = token;
  while (first is ErrorToken) {
    first = first.next!;
  }
  Token before = first.previous!;

  var recorder = EventRecorder();
  var parser = fasta.Parser(
    recorder,
    experimentalFeatures: ExperimentalFeaturesStatus(scanner.featureSet),
  );
  parser.parseUnit(token);

  var stream = <Object?>[];
  Token? t = before.next;
  while (t != null) {
    stream.add([t.offset, t.lexeme, if (t.isSynthetic) t.type.name]);
    if (t.type == TokenType.EOF) break;
    t = t.next;
  }
  return {
    'path': path,
    'events': recorder.events,
    'errors': recorder.errors,
    'stream': stream,
  };
}
