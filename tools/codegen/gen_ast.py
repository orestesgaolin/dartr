    out.append('    /// Dart `AstNode.endToken`.\n')
    out.append(dispatch('pub fn end_token(&self, id: impl Into<NodeId>) -> TokenId', 'self.stores.{store}[slot].end_token(self)'))
    out.append('    /// The child entities in property order (Dart `_childEntities`\n')
    out.append('    /// before `syntacticEntities` sorts them).\n')
    s = []
    s.append('    pub(crate) fn child_entities_unsorted(&self, id: NodeId, out: &mut Vec<Entity>) {\n')
